// scripts/requeue-repointed-players.js
//
// Clears sports.Basketball.statsChecked on exactly the players whose record was
// changed by an alias repoint, so fetch-profile-stats re-fetches them and the
// stale x/c arrays are rebuilt. Writes nothing else.
//
// WHY NOT A SHARD SWEEP
// ─────────────────────
// The obvious route was a forced matrix run over the 44 shards those players sit
// in. That re-fetches every player in those shards - about 70,000 profile fetches
// to correct 24 records. fetch-profile-stats skips anyone carrying statsChecked,
// so deleting that one field from the files that need it puts those players, and
// only those players, back in the queue.
//
// WHO NEEDS IT. Both sides of every repoint:
//   the LOSING player  - games moved off their record, so their x lists games
//                        they no longer hold.
//   the GAINING player - games moved onto it, and their x was computed before
//                        they arrived.
// Working from the losing side alone would leave the other half stale.
//
// THE LIST COMES FROM THE REPORT, not an embedded table. reports/misrouted-
// appearances.json is regenerated by every run of find-misrouted-appearances, so
// a hardcoded copy would be wrong the moment that happens. If the report has been
// regenerated since the apply, this script correctly finds nothing to do rather
// than acting on a stale list.
//
// A player who ALREADY has no statsChecked is left alone and counted separately -
// they are already queued, and rewriting the file to change nothing would put a
// pointless commit in the history.
//
// Run:
//   node scripts/requeue-repointed-players.js
//   node scripts/requeue-repointed-players.js --apply

'use strict';

const fs           = require('fs');
const path         = require('path');
const { execSync } = require('child_process');

const ROOT        = path.join(__dirname, '..');
const PLAYERS_DIR = path.join(ROOT, 'players');
const REPORT_REL  = 'reports/misrouted-appearances.json';
const REPORT_FILE = path.join(ROOT, REPORT_REL);
const SHARDS_FILE = path.join(ROOT, 'refetch-shards.json');

const args  = process.argv.slice(2);
const APPLY = args.includes('--apply');

const log = (m) => console.log(`[requeue] ${new Date().toISOString()} ${m}`);

function playerPath(uuid) {
  return path.join(PLAYERS_DIR, uuid.slice(0, 2).toLowerCase(), `${uuid}.json`);
}

function main() {
  log(`requeue-repointed-players${APPLY ? '' : '  (DRY RUN)'}`);
  console.log('─'.repeat(66));

  let report;
  try { report = JSON.parse(fs.readFileSync(REPORT_FILE, 'utf8')); }
  catch (e) { console.error(`FATAL: cannot read ${REPORT_REL} — ${e.message.split('\n')[0]}`); process.exit(1); }

  const rows = Array.isArray(report.suspectAliases) ? report.suspectAliases : [];
  if (!rows.length) { log('no repoints in the report. Nothing to requeue.'); return; }

  // Both sides, deduplicated: one player can be the losing side of several
  // repoints, and the gaining side of one repoint can be the losing side of
  // another.
  const wanted = new Set();
  for (const r of rows) {
    if (r.currentTarget)       wanted.add(r.currentTarget);
    if (r.likelyCorrectTarget) wanted.add(r.likelyCorrectTarget);
  }
  log(`${rows.length} repoint(s) in the report -> ${wanted.size} distinct player(s)`);

  let cleared = 0, alreadyQueued = 0, missing = 0, noStatsBlock = 0;
  const shards = new Set();
  const touched = [];

  for (const uuid of [...wanted].sort()) {
    const fp = playerPath(uuid);
    let p;
    try { p = JSON.parse(fs.readFileSync(fp, 'utf8')); }
    catch (_) {
      // Expected, and not an error: a player whose every appearance moved away
      // has no games and no stats left, so build-player-games deletes the file.
      missing++; log(`  gone (record collapsed into the other profile): ${uuid.slice(0, 8)}`);
      continue;
    }
    const bk = p.sports && p.sports.Basketball;
    if (!bk)               { noStatsBlock++; continue; }
    if (!bk.statsChecked)  { alreadyQueued++; continue; }

    if (APPLY) {
      delete bk.statsChecked;
      fs.writeFileSync(fp, JSON.stringify(p), 'utf8');   // minified, always
    }
    cleared++;
    shards.add(uuid.slice(0, 2).toLowerCase());
    touched.push({ uuid, name: p.name || null, games: Array.isArray(p.games) ? p.games.length : 0, gp: Number(bk.gp) || 0, x: Array.isArray(bk.x) ? bk.x.length : 0 });
  }

  console.log(`\n  statsChecked cleared${APPLY ? '' : ' (would)'} : ${cleared}`);
  console.log(`  already queued (no statsChecked) : ${alreadyQueued}`);
  console.log(`  file gone (record collapsed)     : ${missing}`);
  console.log(`  no Basketball block              : ${noStatsBlock}`);
  console.log(`  shards involved                  : ${shards.size}`);

  if (touched.length) {
    console.log('\n  players requeued:');
    for (const t of touched.slice(0, 30)) {
      console.log(`    ${t.uuid.slice(0, 8)}  ${String(t.games).padStart(4)} games, gp ${String(t.gp).padStart(4)}, x ${String(t.x).padStart(4)}  ${(t.name || '').slice(0, 26)}`);
    }
    if (touched.length > 30) console.log(`    … and ${touched.length - 30} more`);
  }

  // Always written, always [] outside apply, so a dry run cannot cause a
  // dispatch. Same contract as fold-diverged-players.js.
  fs.writeFileSync(SHARDS_FILE, JSON.stringify(APPLY ? [...shards].sort() : []), 'utf8');
  log(APPLY && shards.size ? `re-fetch queued across ${shards.size} shard(s)` : 're-fetch queued: none');

  if (!APPLY) { log('dry run - no file was modified.'); return; }
  if (!cleared) { log('nothing to commit.'); return; }

  const GIT = { cwd: ROOT, stdio: 'pipe', timeout: 10 * 60 * 1000, maxBuffer: 512 * 1024 * 1024 };
  // Per shard, not `git add players/`: only these files changed and staging the
  // whole tree walks a 419k-file index for nothing.
  for (const shard of shards) execSync(`git add -- players/${shard}`, GIT);
  const staged = execSync('git diff --staged --shortstat', GIT).toString().trim();
  if (!staged) { log('nothing staged.'); return; }
  log(`staging: ${staged}`);
  execSync(`git commit -q -m "requeue-repointed-players: cleared statsChecked on ${cleared} players"`, GIT);
  for (let attempt = 1; attempt <= 60; attempt++) {
    try { execSync('git merge --abort', GIT); } catch {}
    try {
      execSync('git fetch origin main', GIT);
      execSync('git merge -X ours FETCH_HEAD --no-edit --no-stat', GIT);
      execSync('git push origin main', GIT);
      log(`pushed${attempt > 1 ? ` (attempt ${attempt})` : ''}`);
      return;
    } catch (e) {
      log(`push attempt ${attempt}/60 failed: ${e.message.split('\n')[0]}`);
      if (attempt === 60) throw new Error('push failed after 60 attempts');
      execSync(`sleep ${1 + Math.floor(Math.random() * 91)}`, { stdio: 'pipe' });
    }
  }
}

main();
